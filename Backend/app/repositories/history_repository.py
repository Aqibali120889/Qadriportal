    # ── Dashboard Stats ────────────────────────────────────────────────────────

    async def get_history_dashboard_stats(self) -> Dict[str, int]:
        """
        Calculates live activity counts across the system.
        Uses notifications + projects + ocr_jobs as real data sources.
        """
        now = datetime.now(timezone.utc)
        today_start = now.replace(hour=0, minute=0, second=0, microsecond=0)
        # Supabase timestamps are stored WITH timezone, so pass tz-aware datetime.
        # SQLAlchemy ORM comparisons work with naive UTC (stripped tzinfo) for TIMESTAMP WITHOUT TIME ZONE columns.
        # For TEXT queries via asyncpg directly, pass tz-aware. For ORM, pass naive.
        today_start_naive = today_start.replace(tzinfo=None)

        # Today's notifications (most real activity is recorded here)
        # Use raw SQL with NOW() instead of binding a Python datetime to avoid
        # timezone type mismatch between asyncpg and the DB column type.
        t_stmt = text(
            "SELECT COUNT(*) FROM notifications WHERE created_at >= CURRENT_DATE"
        )
        tot_today = (await self._session.execute(t_stmt)).scalar() or 0

        # Total notifications (best proxy for total activities)
        tot_stmt = text("SELECT COUNT(*) FROM notifications")
        tot_all = (await self._session.execute(tot_stmt)).scalar() or 0

        # Also count project events today
        proj_today = text(
            "SELECT COUNT(*) FROM projects WHERE created_at >= CURRENT_DATE OR updated_at >= CURRENT_DATE"
        )
        p_today = (await self._session.execute(proj_today)).scalar() or 0
        tot_today += p_today

        # Active users today (from user_sessions)
        try:
            u_stmt = text(
                "SELECT COUNT(DISTINCT user_id) FROM user_sessions WHERE created_at >= CURRENT_DATE"
            )
            users_today = (await self._session.execute(u_stmt)).scalar() or 0
        except Exception:
            users_today = 0

        # AI jobs today (from ocr_jobs)
        try:
            ai_stmt = text(
                "SELECT COUNT(*) FROM ocr_jobs WHERE created_at >= CURRENT_DATE"
            )
            ai_jobs = (await self._session.execute(ai_stmt)).scalar() or 0
        except Exception:
            ai_jobs = 0

        # Human reviews (from human_reviews via extracted_entities)
        try:
            hr_stmt = text(
                "SELECT COUNT(*) FROM extracted_entities WHERE review_status = 'pending'"
            )
            h_reviews = (await self._session.execute(hr_stmt)).scalar() or 0
        except Exception:
            h_reviews = 0

        # Projects updated today
        pu_stmt = select(func.count()).select_from(Project).where(
            Project.updated_at >= today_start_naive
        )
        p_updated = (await self._session.execute(pu_stmt)).scalar() or 0

        # Kanban changes today (from kanban_tasks)
        try:
            k_stmt = text(
                "SELECT COUNT(*) FROM kanban_tasks WHERE updated_at >= CURRENT_DATE"
            )
            k_changes = (await self._session.execute(k_stmt)).scalar() or 0
        except Exception:
            k_changes = 0

        # Notifications sent today (use CURRENT_DATE to avoid timezone type mismatch)
        n_stmt = text(
            "SELECT COUNT(*) FROM notifications WHERE created_at >= CURRENT_DATE"
        )
        n_sent = (await self._session.execute(n_stmt)).scalar() or 0

        # System events (from system_events if populated, else 0)
        try:
            se_stmt = text("SELECT COUNT(*) FROM system_events WHERE created_at >= CURRENT_DATE")
            sys_events = (await self._session.execute(se_stmt)).scalar() or 0
        except Exception:
            sys_events = 0

        # Security events
        try:
            sec_stmt = text("SELECT COUNT(*) FROM security_events WHERE created_at >= CURRENT_DATE")
            sec_events = (await self._session.execute(sec_stmt)).scalar() or 0
        except Exception:
            sec_events = 0

        return {
            "today_activities": tot_today,
            "total_activities": tot_all,
            "active_users_today": users_today,
            "ai_processing_jobs": ai_jobs,
            "human_reviews": h_reviews,
            "projects_updated": p_updated,
            "kanban_changes": k_changes,
            "notifications_sent": n_sent,
            "system_events": sys_events,
            "security_events": sec_events,
        }

    # ── Unified Activity Feed (Admin / Super Admin) ────────────────────────────

    async def get_unified_activity_feed(
        self,
        *,
        search: Optional[str] = None,
        module: Optional[str] = None,
        severity: Optional[str] = None,
        department_id: Optional[str] = None,
        user_id: Optional[str] = None,
        project_id: Optional[str] = None,
        date_range: Optional[str] = None,
        skip: int = 0,
        limit: int = 25,
    ) -> Tuple[List[Dict[str, Any]], int]:
        """
        Queries notifications + projects tables for a unified activity feed.

        Previously queried system_events (which is empty).
        Now uses notifications + projects as the real data sources.

        department_id=None means Super Admin — returns ALL events.
        department_id=<id> means normal user — scoped to their department.

        Department scoping: notifications.department_id OR
        project.current_department_id (because many notifications have
        department_id=NULL but the related project has current_department_id).
        """
        # ── Source 1: notifications ────────────────────────────────────────────
        notif_query = text("""
            SELECT
                n.id,
                n.event_type,
                n.notification_type,
                n.title,
                n.message,
                n.created_at,
                n.user_id AS performed_by,
                COALESCE(u.first_name || ' ' || u.last_name, u.email, 'System') AS user_name,
                u.email AS user_email,
                COALESCE(d.name, d2.name, 'General') AS department_name,
                p.id AS project_id,
                p.job_number,
                p.title AS project_title,
                COALESCE(n.department_id, p.current_department_id) AS effective_dept_id
            FROM notifications n
            LEFT JOIN users u ON u.id = n.user_id
            LEFT JOIN departments d ON d.id = n.department_id
            LEFT JOIN projects p ON p.id = n.project_id
            LEFT JOIN departments d2 ON d2.id = p.current_department_id
            ORDER BY n.created_at DESC
        """)

        # ── Source 2: projects (lifecycle events) ──────────────────────────────
        proj_query = text("""
            SELECT
                p.id,
                'project_created' AS event_type,
                'INFO' AS notification_type,
                COALESCE('Project ' || p.job_number || ' created', 'Project created') AS title,
                p.title AS message,
                p.created_at,
                p.created_by AS performed_by,
                COALESCE(u.first_name || ' ' || u.last_name, u.email) AS user_name,
                u.email AS user_email,
                COALESCE(d.name, 'General') AS department_name,
                p.id AS project_id,
                p.job_number,
                p.title AS project_title,
                p.current_department_id AS effective_dept_id
            FROM projects p
            LEFT JOIN users u ON u.id = p.created_by
            LEFT JOIN departments d ON d.id = p.current_department_id
            ORDER BY p.created_at DESC
        """)

        now = datetime.now(timezone.utc)

        # Execute both queries
        notif_rows = (await self._session.execute(notif_query)).fetchall()
        proj_rows = (await self._session.execute(proj_query)).fetchall()

        # Also try system_events if populated
        sys_rows = []
        try:
            sys_q = text("""
                SELECT
                    se.id, se.event_type, se.severity::text,
                    COALESCE(se.description, se.event_type) AS title,
                    se.description AS message,
                    se.created_at,
                    se.performed_by,
                    COALESCE(u.first_name || ' ' || u.last_name, u.email) AS user_name,
                    u.email AS user_email,
                    COALESCE(d.name, 'General') AS department_name,
                    p.id AS project_id,
                    p.job_number,
                    p.title AS project_title,
                    u.department_id AS effective_dept_id
                FROM system_events se
                LEFT JOIN users u ON u.id = se.performed_by
                LEFT JOIN departments d ON d.id = u.department_id
                LEFT JOIN projects p ON p.id = se.project_id
                ORDER BY se.created_at DESC
            """)
            sys_rows = (await self._session.execute(sys_q)).fetchall()
        except Exception:
            pass

        items: List[Dict[str, Any]] = []

        # ── Process notification rows ──────────────────────────────────────────
        for r in notif_rows:
            created_at = _tz_aware(r[5])

            # Date range filter
            if date_range == "Today" and created_at:
                day_start = now.replace(hour=0, minute=0, second=0, microsecond=0)
                if created_at < day_start:
                    continue
            if date_range == "Yesterday" and created_at:
                day_start = now.replace(hour=0, minute=0, second=0, microsecond=0)
                yest_start = day_start - timedelta(days=1)
                if created_at < yest_start or created_at >= day_start:
                    continue

            # Department filter — only when explicitly provided (normal users)
            if department_id:
                effective = str(r[13]) if r[13] else None
                if effective != department_id:
                    continue

            # User filter
            if user_id and str(r[6]) != user_id:
                continue

            # Project filter
            if project_id and str(r[10]) != project_id:
                continue

            # Module filter (map event_type to module)
            ev_type = r[1] or "notification"
            item_module = _EVENT_TYPE_TO_MODULE.get(ev_type, "System")
            if module and module.lower() != "all" and item_module.lower() != module.lower():
                continue

            # Severity filter
            notif_type = str(r[2] or "INFO").upper()
            item_severity = _NOTIF_TYPE_TO_SEVERITY.get(notif_type, "INFO")
            if severity and severity.lower() != "all" and item_severity.lower() != severity.lower():
                continue

            # Search
            title = r[3] or ""
            desc_text = r[4] or ""
            job = r[11] or ""
            if search:
                s = search.lower()
                if s not in title.lower() and s not in desc_text.lower() and s not in job.lower():
                    continue

            user_name = r[7] or "System"
            initials = "".join([p[0].upper() for p in user_name.split()[:2]]) if user_name else "SY"

            items.append({
                "id": str(r[0]),
                "event_type": ev_type,
                "module": item_module,
                "entity_name": "Notification",
                "entity_id": str(r[0]),
                "description": title,
                "severity": item_severity,
                "timestamp": created_at.strftime("%I:%M %p") if created_at else "—",
                "date_group": created_at.strftime("%b %d, %Y") if created_at else "Earlier",
                "created_at": created_at.isoformat() if created_at else None,
                "performed_by": str(r[6]) if r[6] else None,
                "user": user_name,
                "user_initials": initials,
                "department": r[9] or "General",
                "project_id": str(r[10]) if r[10] else None,
                "job_number": r[11],
                "project_title": r[12],
            })

        # ── Process project lifecycle rows ─────────────────────────────────────
        for r in proj_rows:
            created_at = _tz_aware(r[5])

            # Date range filter
            if date_range == "Today" and created_at:
                day_start = now.replace(hour=0, minute=0, second=0, microsecond=0)
                if created_at < day_start:
                    continue
            if date_range == "Yesterday" and created_at:
                day_start = now.replace(hour=0, minute=0, second=0, microsecond=0)
                yest_start = day_start - timedelta(days=1)
                if created_at < yest_start or created_at >= day_start:
                    continue

            # Department filter
            if department_id:
                effective = str(r[13]) if r[13] else None
                if effective != department_id:
                    continue

            # User filter
            if user_id and str(r[6]) != user_id:
                continue

            # Project filter
            if project_id and str(r[10]) != project_id:
                continue

            # Module filter
            item_module = "Projects"
            if module and module.lower() != "all" and item_module.lower() != module.lower():
                continue

            # Severity filter (project events are always INFO)
            if severity and severity.lower() != "all" and severity.lower() != "info":
                continue

            title = r[3] or ""
            job = r[11] or ""
            if search:
                s = search.lower()
                if s not in title.lower() and s not in job.lower():
                    continue

            user_name = r[7] or "System"
            initials = "".join([p[0].upper() for p in user_name.split()[:2]]) if user_name else "SY"

            items.append({
                "id": str(r[0]) + "_created",
                "event_type": "project_created",
                "module": "Projects",
                "entity_name": "Project",
                "entity_id": str(r[0]),
                "description": title,
                "severity": "INFO",
                "timestamp": created_at.strftime("%I:%M %p") if created_at else "—",
                "date_group": created_at.strftime("%b %d, %Y") if created_at else "Earlier",
                "created_at": created_at.isoformat() if created_at else None,
                "performed_by": str(r[6]) if r[6] else None,
                "user": user_name,
                "user_initials": initials,
                "department": r[9] or "General",
                "project_id": str(r[10]) if r[10] else None,
                "job_number": r[11],
                "project_title": r[12],
            })

        # ── Process system_events rows (if any) ────────────────────────────────
        for r in sys_rows:
            created_at = _tz_aware(r[5])

            if date_range == "Today" and created_at:
                day_start = now.replace(hour=0, minute=0, second=0, microsecond=0)
                if created_at < day_start:
                    continue

            if department_id:
                effective = str(r[13]) if r[13] else None
                if effective != department_id:
                    continue

            if project_id and str(r[10]) != project_id:
                continue

            title = r[3] or r[1] or ""
            if search:
                s = search.lower()
                if s not in title.lower():
                    continue

            user_name = r[7] or "System"
            initials = "".join([p[0].upper() for p in user_name.split()[:2]]) if user_name else "SY"

            items.append({
                "id": str(r[0]),
                "event_type": r[1] or "system",
                "module": _EVENT_TYPE_TO_MODULE.get(r[1] or "", "System"),
                "entity_name": "System",
                "entity_id": str(r[0]),
                "description": title,
                "severity": str(r[2] or "INFO").upper(),
                "timestamp": created_at.strftime("%I:%M %p") if created_at else "—",
                "date_group": created_at.strftime("%b %d, %Y") if created_at else "Earlier",
                "created_at": created_at.isoformat() if created_at else None,
                "performed_by": str(r[6]) if r[6] else None,
                "user": user_name,
                "user_initials": initials,
                "department": r[9] or "General",
                "project_id": str(r[10]) if r[10] else None,
                "job_number": r[11],
                "project_title": r[12],
            })

        # Sort combined items by created_at descending
        items.sort(key=lambda x: x.get("created_at") or "", reverse=True)

        total = len(items)
        paginated_items = items[skip: skip + limit]
        return paginated_items, total

    # ── Department-Scoped Feed (Cost Estimation / Foundry pages) ──────────────

    async def get_department_feed(
        self,
        department_id: Optional[str],
        skip: int = 0,
        limit: int = 20,
    ) -> Tuple[List[Dict[str, Any]], int]:
        """
        Department-scoped activity feed. Merges notifications + project events
        for the given department. When department_id=None (Super Admin), returns
        all events.

        Consumed by GET /api/v1/history.

        Department matching strategy (in priority order):
          1. notifications.department_id = department_id (direct match)
          2. projects.current_department_id = department_id (via project_id FK)
          3. If department_id is None → include all (Super Admin)
        """
        # Build notifications query for this department
        if department_id:
            notif_stmt = text("""
                SELECT
                    n.id, n.event_type, n.notification_type,
                    n.title, n.message, n.created_at, n.project_id,
                    p.job_number
                FROM notifications n
                LEFT JOIN projects p ON p.id = n.project_id
                WHERE
                    n.department_id::text = :dept_id
                    OR p.current_department_id::text = :dept_id
                    OR (n.metadata->>'from_department_id' = :dept_id OR n.metadata->>'to_department_id' = :dept_id)
                ORDER BY n.created_at DESC
                LIMIT :lim OFFSET :skip
            """)
            count_stmt = text("""
                SELECT COUNT(*) FROM notifications n
                LEFT JOIN projects p ON p.id = n.project_id
                WHERE
                    n.department_id::text = :dept_id
                    OR p.current_department_id::text = :dept_id
                    OR (n.metadata->>'from_department_id' = :dept_id OR n.metadata->>'to_department_id' = :dept_id)
            """)
            params = {"dept_id": department_id, "lim": limit, "skip": skip}
            count_params = {"dept_id": department_id}
        else:
            # Super Admin — all notifications
            notif_stmt = text("""
                SELECT
                    n.id, n.event_type, n.notification_type,
                    n.title, n.message, n.created_at, n.project_id,
                    p.job_number
                FROM notifications n
                LEFT JOIN projects p ON p.id = n.project_id
                ORDER BY n.created_at DESC
                LIMIT :lim OFFSET :skip
            """)
            count_stmt = text("SELECT COUNT(*) FROM notifications")
            params = {"lim": limit, "skip": skip}
            count_params = {}

        rows = (await self._session.execute(notif_stmt, params)).fetchall()
        total = (await self._session.execute(count_stmt, count_params)).scalar() or 0

        formatted_items = []
        for r in rows:
            created_at = _tz_aware(r[5])

            formatted_items.append({
                "id": str(r[0]),
                "event_type": r[1] or "notification",
                "title": r[3] or r[1] or "Activity",
                "message": r[4],
                "project_id": str(r[6]) if r[6] else None,
                "job_number": r[7],
                "notification_type": str(r[2] or "INFO").upper(),
                "status": None,
                "created_at": created_at,
            })

        return formatted_items, total

    # ── Project Timeline (per-project history) ─────────────────────────────────

    async def get_project_timeline(self, project_id: str) -> List[Dict[str, Any]]:
        """
        Returns ordered project timeline events for a given project.
        Queries notifications (primary source) + system_events (if populated).
        """
        # Primary source: notifications
        notif_stmt = text("""
            SELECT
                n.id, n.event_type, n.notification_type,
                n.title AS description,
                n.created_at,
                NULL AS user_name
            FROM notifications n
            WHERE n.project_id = :pid
            ORDER BY n.created_at ASC
        """)
        notif_rows = (await self._session.execute(notif_stmt, {"pid": project_id})).fetchall()

        # Secondary source: system_events (if they ever get populated)
        sys_rows = []
        try:
            sys_stmt = text("""
                SELECT
                    se.id, se.event_type, se.severity::text,
                    se.description, se.created_at,
                    COALESCE(u.first_name || ' ' || u.last_name, 'System') as user_name
                FROM system_events se
                LEFT JOIN users u ON u.id = se.performed_by
                WHERE se.project_id = :pid OR (se.entity_name = 'Project' AND se.entity_id = :pid)
                ORDER BY se.created_at ASC
            """)
            sys_rows = (await self._session.execute(sys_stmt, {"pid": project_id})).fetchall()
        except Exception:
            pass

        results = []

        for r in notif_rows:
            created_at = _tz_aware(r[4])
            results.append({
                "id": str(r[0]),
                "event_type": r[1] or "notification",
                "module": _EVENT_TYPE_TO_MODULE.get(r[1] or "", "System"),
                "description": r[3] or r[1] or "Activity",
                "severity": _NOTIF_TYPE_TO_SEVERITY.get(str(r[2] or "INFO").upper(), "INFO"),
                "created_at": created_at.isoformat() if created_at else None,
                "user": r[5] or "System",
            })

        for r in sys_rows:
            created_at = _tz_aware(r[4])
            results.append({
                "id": str(r[0]),
                "event_type": r[1] or "system",
                "module": _EVENT_TYPE_TO_MODULE.get(r[1] or "", "System"),
                "description": r[3] or r[1] or "System Event",
                "severity": str(r[2] or "INFO").upper(),
                "created_at": created_at.isoformat() if created_at else None,
                "user": r[5] or "System",
            })

        # Sort combined by created_at ascending (timeline order)
        results.sort(key=lambda x: x.get("created_at") or "")
        return results

    # ── User Timeline ──────────────────────────────────────────────────────────

    async def get_user_timeline(self, user_id: str) -> List[Dict[str, Any]]:
        """Returns ordered user activity timeline events."""
        # Try system_events first (may be empty)
        try:
            stmt = text("""
                SELECT id, event_type, module, description, severity, created_at
                FROM system_events
                WHERE performed_by = :uid
                ORDER BY created_at DESC
                LIMIT 50
            """)
            res = await self._session.execute(stmt, {"uid": user_id})
            rows = res.fetchall()
            if rows:
                return [
                    {
                        "id": str(r[0]),
                        "event_type": r[1],
                        "module": r[2],
                        "description": r[3],
                        "severity": str(r[4]).upper() if r[4] else "INFO",
                        "created_at": _tz_aware(r[5]).isoformat() if r[5] else None,
                    }
                    for r in rows
                ]
        except Exception:
            pass

        # Fallback: login_history for the user
        try:
            lh_stmt = text("""
                SELECT id, 'user_login' AS event_type, 'Security' AS module,
                       COALESCE('Login ' || login_status, 'Login event') AS description,
                       CASE WHEN login_status = 'SUCCESS' THEN 'INFO' ELSE 'WARNING' END AS severity,
                       login_time AS created_at
                FROM login_history
                WHERE user_id = :uid
                ORDER BY login_time DESC
                LIMIT 50
            """)
            res2 = await self._session.execute(lh_stmt, {"uid": user_id})
            rows2 = res2.fetchall()
            return [
                {
                    "id": str(r[0]),
                    "event_type": r[1],
                    "module": r[2],
                    "description": r[3],
                    "severity": r[4],
                    "created_at": _tz_aware(r[5]).isoformat() if r[5] else None,
                }
                for r in rows2
            ]
        except Exception:
            return []

    # ── Activity Detail (for drawer) ──────────────────────────────────────────

    async def get_activity_by_id(self, activity_id: str) -> Optional[Dict[str, Any]]:
        """
        Returns activity details with optional old/new data diff.
        Checks notifications first (primary source), then system_events.
        """
        # Try notifications first — join users so we get a real actor name
        notif_stmt = text("""
            SELECT
                n.id, n.event_type, n.notification_type,
                'Notification' AS entity_name, n.id AS entity_id,
                COALESCE(n.title, n.event_type) AS description,
                n.notification_type AS severity,
                n.created_at,
                n.user_id AS performed_by,
                COALESCE(
                    u.first_name || ' ' || u.last_name,
                    u.email,
                    'System'
                ) AS user_name,
                COALESCE(d.name, d2.name, 'General') AS department_name,
                p.job_number, p.title AS project_title,
                NULL AS old_data, NULL AS new_data
            FROM notifications n
            LEFT JOIN users u ON u.id = n.user_id
            LEFT JOIN projects p ON p.id = n.project_id
            LEFT JOIN departments d ON d.id = n.department_id
            LEFT JOIN departments d2 ON d2.id = p.current_department_id
            WHERE n.id = :aid
        """)

        # Strip _created suffix used for project lifecycle entries
        clean_id = activity_id.replace("_created", "")

        res = await self._session.execute(notif_stmt, {"aid": clean_id})
        row = res.fetchone()

        if row:
            created_at = _tz_aware(row[7])
            user_name = str(row[9]).strip() if row[9] else "System"
            return {
                "id": str(row[0]),
                "event_type": row[1] or "notification",
                "module": _EVENT_TYPE_TO_MODULE.get(row[1] or "", "System"),
                "entity_name": row[3],
                "entity_id": str(row[4]) if row[4] else None,
                "description": row[5],
                "severity": _NOTIF_TYPE_TO_SEVERITY.get(str(row[6] or "INFO").upper(), "INFO"),
                "created_at": created_at.isoformat() if created_at else None,
                "performed_by": str(row[8]) if row[8] else None,
                "user": user_name or "System",
                "department": row[10] or "General",
                "job_number": row[11],
                "project_title": row[12],
                "old_data": row[13],
                "new_data": row[14],
            }

        # Try project lifecycle entry
        if activity_id.endswith("_created"):
            proj_stmt = text("""
                SELECT p.id, p.job_number, p.title, p.created_at, p.created_by,
                       COALESCE(u.first_name || ' ' || u.last_name, u.email, 'System') AS user_name,
                       COALESCE(d.name, 'General') AS department_name
                FROM projects p
                LEFT JOIN users u ON u.id = p.created_by
                LEFT JOIN departments d ON d.id = p.current_department_id
                WHERE p.id = :pid
            """)
            res2 = await self._session.execute(proj_stmt, {"pid": clean_id})
            row2 = res2.fetchone()
            if row2:
                created_at = _tz_aware(row2[3])
                return {
                    "id": activity_id,
                    "event_type": "project_created",
                    "module": "Projects",
                    "entity_name": "Project",
                    "entity_id": str(row2[0]),
                    "description": f"Project {row2[1]} created",
                    "severity": "INFO",
                    "created_at": created_at.isoformat() if created_at else None,
                    "performed_by": str(row2[4]) if row2[4] else None,
                    "user": row2[5],
                    "department": row2[6],
                    "job_number": row2[1],
                    "project_title": row2[2],
                    "old_data": None,
                    "new_data": None,
                }

        # Try system_events as last resort
        try:
            sys_stmt = text("""
                SELECT
                    se.id, se.event_type, se.module, se.entity_name, se.entity_id,
                    se.description, se.severity, se.created_at, se.performed_by,
                    COALESCE(u.first_name || ' ' || u.last_name, u.email, 'System') as user_name,
                    d.name as department_name, p.job_number, p.title as project_title,
                    ea.old_data, ea.new_data
                FROM system_events se
                LEFT JOIN users u ON u.id = se.performed_by
                LEFT JOIN departments d ON d.id = u.department_id
                LEFT JOIN projects p ON p.id = se.project_id
                LEFT JOIN entity_audit_logs ea ON (
                    ea.entity_id = se.entity_id
                    AND ea.changed_at >= se.created_at - INTERVAL '5 seconds'
                    AND ea.changed_at <= se.created_at + INTERVAL '5 seconds'
                )
                WHERE se.id = :aid
            """)
            res3 = await self._session.execute(sys_stmt, {"aid": clean_id})
            row3 = res3.fetchone()
            if row3:
                created_at = _tz_aware(row3[7])
                return {
                    "id": str(row3[0]),
                    "event_type": row3[1],
                    "module": row3[2],
                    "entity_name": row3[3],
                    "entity_id": str(row3[4]) if row3[4] else None,
                    "description": row3[5],
                    "severity": str(row3[6]).upper() if row3[6] else "INFO",
                    "created_at": created_at.isoformat() if created_at else None,
                    "performed_by": str(row3[8]) if row3[8] else None,
                    "user": row3[9],
                    "department": row3[10] or "General",
                    "job_number": row3[11],
                    "project_title": row3[12],
                    "old_data": row3[13],
                    "new_data": row3[14],
                }
        except Exception:
            pass

        return None
